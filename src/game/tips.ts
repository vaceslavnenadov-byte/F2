const KEY = 'wasteland2241.tipsShown';

export function tipShown(id: string): boolean {
  try {
    return (JSON.parse(localStorage.getItem(KEY) ?? '[]') as string[]).includes(id);
  } catch {
    return true;
  }
}

export function markTip(id: string) {
  try {
    const list = JSON.parse(localStorage.getItem(KEY) ?? '[]') as string[];
    if (!list.includes(id)) list.push(id);
    localStorage.setItem(KEY, JSON.stringify(list));
  } catch {
    /* без хранилища подсказка может повториться */
  }
}

export function resetTips() {
  try {
    localStorage.removeItem(KEY);
  } catch {
    /* ничего страшного */
  }
}
